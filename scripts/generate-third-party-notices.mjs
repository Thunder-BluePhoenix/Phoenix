// Generates THIRD_PARTY_NOTICES.md: the licence text of every third-party package that ships.
//
//   node scripts/generate-third-party-notices.mjs           write the file
//   node scripts/generate-third-party-notices.mjs --check   fail if the file is out of date
//
// Sources, both read from lockfiles so the output is reproducible:
//   npm   production packages from `pnpm licenses list --prod` (licence text read from the package)
//   Rust  every crate in apps/desktop/src-tauri/Cargo.lock (`cargo metadata`, licence files from
//         the local cargo registry; run `cargo fetch` first on a clean machine)
// Rust crates are listed for every target, so the file is a superset of any one build.
import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname;
const OUT = join(ROOT, "THIRD_PARTY_NOTICES.md");
const LICENSE_FILE = /^(licen[sc]e|copying|unlicen[sc]e|notice)(-|_|\.|$)/i;

const run = (cmd, args, cwd) =>
  execFileSync(cmd, args, { cwd, encoding: "utf8", maxBuffer: 256 * 1024 * 1024 });

function licenseTexts(dir) {
  if (!dir || !existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => LICENSE_FILE.test(f))
    .sort()
    .map((f) => ({ file: f, text: readFileSync(join(dir, f), "utf8").trim() }))
    .filter((t) => t.text.length > 0);
}

function npmPackages() {
  const pnpm = process.env.PNPM ? process.env.PNPM.split(" ") : ["pnpm"];
  const json = run(pnpm[0], [...pnpm.slice(1), "licenses", "list", "--prod", "--json"], ROOT);
  return Object.values(JSON.parse(json))
    .flat()
    .flatMap((p) =>
      p.versions.map((version, i) => ({
        kind: "npm",
        name: p.name,
        version,
        license: p.license,
        homepage: p.homepage,
        dir: p.paths[i] ?? p.paths[0],
      })),
    );
}

function rustPackages() {
  const cwd = join(ROOT, "apps/desktop/src-tauri");
  const meta = JSON.parse(run("cargo", ["metadata", "--format-version", "1", "--locked"], cwd));
  const own = new Set(meta.workspace_members);
  return meta.packages
    .filter((p) => !own.has(p.id))
    .map((p) => ({
      kind: "rust",
      name: p.name,
      version: p.version,
      license: p.license ?? "(none declared)",
      homepage: p.homepage ?? p.repository ?? "",
      dir: dirname(p.manifest_path),
    }));
}

const byName = (a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version);

export function build() {
  const packages = [...npmPackages().sort(byName), ...rustPackages().sort(byName)];
  const missing = [];

  // Many packages ship the identical text; print each distinct text once.
  const texts = new Map();
  const entries = packages.map((p) => {
    const found = licenseTexts(p.dir);
    if (found.length === 0) missing.push(p);
    const ids = found.map((t) => {
      let id = [...texts.keys()].find((k) => texts.get(k).text === t.text);
      if (!id) {
        id = `L${texts.size + 1}`;
        texts.set(id, { text: t.text, users: [] });
      }
      texts.get(id).users.push(`${p.name} ${p.version}`);
      return id;
    });
    return { ...p, ids };
  });

  const lines = [
    "# Third-party notices",
    "",
    "Phoenix is licensed under the GNU General Public License v3.0 ([LICENSE](LICENSE)).",
    "It includes the third-party software listed below, under the licences shown.",
    "This file is generated by `scripts/generate-third-party-notices.mjs`; do not edit it by hand.",
    "",
    `${entries.filter((e) => e.kind === "npm").length} npm packages (production only) and ` +
      `${entries.filter((e) => e.kind === "rust").length} Rust crates (every target the desktop ` +
      "app can be built for, so a given build ships a subset).",
    "",
    "## Packages",
    "",
    "| Package | Version | Licence | Text |",
    "| --- | --- | --- | --- |",
    ...entries.map(
      (e) =>
        `| ${e.name} (${e.kind}) | ${e.version} | ${e.license.replaceAll("|", "\\|")} | ` +
        `${e.ids.length ? e.ids.join(", ") : "see below"} |`,
    ),
    "",
    ...(missing.length === 0
      ? []
      : [
          "## Packages that ship no licence file",
          "",
          "These packages declare their licence in their manifest but include no licence file. ",
          "The declared licence is shown; the text is the standard text for that licence, ",
          "and the copyright holders are listed in each project's repository.",
          "",
          "| Package | Version | Declared licence | Source |",
          "| --- | --- | --- | --- |",
          ...missing.map(
            (p) =>
              `| ${p.name} | ${p.version} | ${p.license.replaceAll("|", "\\|")} | ${p.homepage || "(none listed)"} |`,
          ),
          "",
        ]),
    "## Licence texts",
    "",
    ...[...texts.entries()].flatMap(([id, { text, users }]) => [
      `### ${id}`,
      "",
      `Used by: ${users.length > 6 ? `${users.slice(0, 6).join(", ")} and ${users.length - 6} more` : users.join(", ")}`,
      "",
      "```text",
      text,
      "```",
      "",
    ]),
  ];
  return { markdown: lines.join("\n"), missing, count: entries.length, distinct: texts.size };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const { markdown, missing, count, distinct } = build();
  if (process.argv.includes("--check")) {
    const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
    if (current !== markdown) {
      console.error(
        "THIRD_PARTY_NOTICES.md is out of date. Run: node scripts/generate-third-party-notices.mjs",
      );
      process.exit(1);
    }
    console.log(`THIRD_PARTY_NOTICES.md is up to date (${count} packages)`);
  } else {
    writeFileSync(OUT, markdown);
    console.log(
      `wrote THIRD_PARTY_NOTICES.md: ${count} packages, ${distinct} distinct licence texts`,
    );
  }
  if (missing.length > 0) {
    console.warn(
      `${missing.length} packages ship no licence file (their licence is listed by name only):\n  ` +
        missing.map((p) => `${p.name} ${p.version} (${p.license})`).join("\n  "),
    );
  }
}
