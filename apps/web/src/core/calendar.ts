/** Owner-visible calendar data. Private events contain no identifying metadata. */
export interface CalendarEventView {
  id: string;
  title: string;
  start: string;
  end: string;
  timezone: string;
  url?: string;
  private: boolean;
  deployFreeze?: boolean;
}

export interface CalendarPrepSource {
  text: string;
  href: string;
  meetingTitle: string;
}

export interface CalendarMeetingPrep {
  decisions: CalendarPrepSource[];
  actionItems: CalendarPrepSource[];
}

/**
 * `ready`: a fresh feed was read. Every other status means the event list is empty because the feed
 * cannot be trusted, not because nothing is scheduled.
 */
export type CalendarFeedStatus = "ready" | "unconfigured" | "unavailable" | "stale";

export interface CalendarUpcomingView {
  enabled: boolean;
  status: CalendarFeedStatus;
  /** Epoch ms of the feed read the events came from; null when there is none. */
  checkedAt: number | null;
  /** False when some events have no prep computed. */
  prepComplete: boolean;
  events: CalendarEventView[];
  prep: Record<string, CalendarMeetingPrep>;
}

/** External links must not permit script, local-file or credential-bearing URLs. */
export function calendarLink(value: string | undefined): string | undefined {
  if (!value || !URL.canParse(value)) return undefined;
  const url = new URL(value);
  return url.protocol === "https:" && !url.username && !url.password ? url.href : undefined;
}

/** Prep sources are generated by Core as local meeting links; never follow arbitrary API URLs. */
export function prepLink(value: string): string | undefined {
  if (!value.startsWith("#/meetings/")) return undefined;
  const id = value.slice("#/meetings/".length);
  return id && !/[/?#]/.test(id) ? value : undefined;
}
